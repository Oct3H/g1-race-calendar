import assert from 'node:assert/strict';
import { createUnopenedShop, activateShop, accrueShopBank } from '../design/shop-start-preview.mjs';
import { addBankDays, withdraw } from '../design/game-state.mjs';

const state = createUnopenedShop();
assert.deepEqual([state.cash, state.bank, state.shopActivated, state.detailBetEntry], [0, 0, false, false]);
addBankDays(state, 100);
accrueShopBank(state, new Date('2026-10-24T04:00:00Z'), 'Asia/Shanghai');
assert.deepEqual([state.cash, state.bank, state.bankDays, state.firstShopOpenedAt], [0, 0, 0, null]);
assert.equal(activateShop(state, new Date('2026-10-24T04:00:00Z'), 'Asia/Shanghai'), true);
assert.deepEqual([state.cash, state.bank, state.bankAnchorDay, state.detailBetEntry], [500000, 0, '2026-10-24', false]);
assert.equal(state.bankTimeZone, 'Asia/Shanghai');
assert.equal(activateShop(state, new Date('2026-10-27T04:00:00Z'), 'Asia/Shanghai'), false);
assert.equal(state.cash, 500000);
accrueShopBank(state, new Date('2026-10-24T15:59:59Z'), 'Asia/Shanghai');
assert.equal(state.bank, 0);
accrueShopBank(state, new Date('2026-10-27T04:00:00Z'), 'Asia/Shanghai');
assert.equal(state.bank, 30000);
assert.equal(state.firstShopOpenedAt, '2026-10-24T04:00:00.000Z');
accrueShopBank(state, new Date('2026-10-27T04:00:00Z'), 'Asia/Shanghai');
assert.equal(state.bank, 30000);
withdraw(state, 30000);
accrueShopBank(state, new Date('2026-10-27T04:00:00Z'), 'Asia/Shanghai');
assert.equal(state.bank, 0);
assert.equal(state.cash, 530000);
accrueShopBank(state, new Date('2027-10-27T04:00:00Z'), 'Asia/Shanghai');
assert.equal(state.bank, 1000000);
const dst = createUnopenedShop();
activateShop(dst, new Date('2026-03-07T17:00:00Z'), 'America/New_York');
accrueShopBank(dst, new Date('2026-03-09T16:00:00Z'), 'America/New_York');
assert.equal(dst.bank, 20000, 'local calendar days, not elapsed 24-hour blocks');
const fixedZone = createUnopenedShop();
const beforeShanghaiMidnight = new Date('2026-10-24T15:30:00Z');
activateShop(fixedZone, beforeShanghaiMidnight, 'Asia/Shanghai');
assert.equal(activateShop(fixedZone, beforeShanghaiMidnight, 'Asia/Tokyo'), false);
accrueShopBank(fixedZone, beforeShanghaiMidnight);
assert.equal(fixedZone.bankTimeZone, 'Asia/Shanghai');
assert.equal(fixedZone.bank, 0, 'Tokyo is already on the next date, but bank still follows its original Shanghai date');
accrueShopBank(fixedZone, new Date('2026-10-24T16:00:00Z'));
assert.equal(fixedZone.bank, 10000);
accrueShopBank(fixedZone, beforeShanghaiMidnight);
assert.equal(fixedZone.bank, 10000, 'earlier dates do not reset the accrued-through date');
accrueShopBank(fixedZone, new Date('2026-10-24T16:00:00Z'));
assert.equal(fixedZone.bank, 10000, 'returning to the paid date does not pay it twice');
console.log('PASS: unopened cash/bank zero, no prior accrual, first shop grant once, bank begins next local date, repeated opens/checks/withdrawals do not regrant, cap and DST dates.');
